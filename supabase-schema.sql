-- SQL for Supabase trading_signals table
-- Run this in: Supabase Dashboard → SQL Editor → Run

CREATE TABLE IF NOT EXISTS trading_signals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  signal_type TEXT NOT NULL CHECK (signal_type IN ('breakout', 'reversal', 'trend', 'scalping')),
  symbol TEXT NOT NULL,
  action TEXT NOT NULL CHECK (action IN ('buy', 'sell', 'close')),
  price NUMERIC NOT NULL,
  quantity NUMERIC NOT NULL,
  timestamp TIMESTAMPTZ DEFAULT NOW(),
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'executing', 'executed', 'failed', 'cancelled')),
  strategy TEXT,
  confidence NUMERIC CHECK (confidence >= 0 AND confidence <= 1),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS
ALTER TABLE trading_signals ENABLE ROW LEVEL SECURITY;

-- Policies
CREATE POLICY IF NOT EXISTS "allow_insert" ON trading_signals FOR INSERT WITH CHECK (true);
CREATE POLICY IF NOT EXISTS "allow_select" ON trading_signals FOR SELECT USING (true);
CREATE POLICY IF NOT EXISTS "allow_update" ON trading_signals FOR UPDATE USING (true);

-- Trigger to update updated_at
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE 'plpgsql';

CREATE TRIGGER update_trading_signals_updated_at BEFORE UPDATE ON trading_signals FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

-- Create execution_logs table
CREATE TABLE IF NOT EXISTS execution_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  signal_id BIGINT REFERENCES trading_signals(id),
  message TEXT,
  level TEXT DEFAULT 'info' CHECK (level IN ('debug', 'info', 'warn', 'error')),
  api_response JSONB,
  error_details JSONB,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Create positions table
CREATE TABLE IF NOT EXISTS positions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  symbol TEXT NOT NULL,
  position_size NUMERIC NOT NULL,
  entry_price NUMERIC,
  current_price NUMERIC,
  pnl NUMERIC,
  status TEXT DEFAULT 'open' CHECK (status IN ('open', 'closed', 'liquidated')),
  opened_at TIMESTAMPTZ DEFAULT NOW(),
  closed_at TIMESTAMPTZ,
  strategy TEXT
);

-- Create orders table
CREATE TABLE IF NOT EXISTS orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  signal_id BIGINT REFERENCES trading_signals(id),
  order_type TEXT NOT NULL CHECK (order_type IN ('market', 'limit', 'stop')),
  side TEXT NOT NULL CHECK (side IN ('buy', 'sell')),
  symbol TEXT NOT NULL,
  qty NUMERIC NOT NULL,
  price NUMERIC,
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'filled', 'rejected', 'cancelled')),
  order_id TEXT,
  client_order_id TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);