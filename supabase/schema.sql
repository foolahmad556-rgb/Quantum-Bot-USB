-- Supabase Schema for QuantumBot-USB
-- This schema defines the tables for storing trading data, user state, and bot configuration.

-- Enable UUID extension if not already enabled
create extension if not exists "uuid-ossp";

-- Table: users
-- Stores user information and API keys (encrypted)
create table if not exists users (
  id uuid primary key default uuid_generate_v4(),
  email text unique not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null,
  -- Encrypted API keys (store as text, encryption handled at application level)
  binance_api_key text,
  binance_api_secret text,
  telegram_bot_token text,
  telegram_channel_id text,
  -- Trading preferences
  execution_mode text default 'PAPER' check (execution_mode in ('PAPER', 'TESTNET', 'LIVE')),
  auto_start_trading boolean default false,
  confirm_live_trading boolean default false,
  allow_min_notional_bump boolean default false
);

-- Table: trading_state
-- Stores the current state of the trading bot for each user
create table if not exists trading_state (
  id uuid primary key default uuid_generate_v4(),
  user_id uuid references users(id) on delete cascade not null,
  is_running boolean default false,
  current_strategy text,
  last_signal timestamp with time zone,
  last_order_id text,
  last_order_status text,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Table: orders
-- Records of all orders placed by the bot
create table if not exists orders (
  id uuid primary key default uuid_generate_v4(),
  user_id uuid references users(id) on delete cascade not null,
  client_order_id text unique,
  exchange_order_id text,
  symbol text not null,
  side text not null check (side in ('BUY', 'SELL')),
  type text not null, -- e.g., LIMIT, MARKET, STOP_LOSS, TAKE_PROFIT
  quantity decimal(20,8) not null,
  price decimal(20,8),
  stop_price decimal(20,8),
  status text not null, -- e.g., NEW, PARTIALLY_FILLED, FILLED, CANCELED, REJECTED, EXPIRED
  timestamp timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null,
  fee decimal(20,8) default 0,
  fee_asset text,
  -- Additional metadata
  strategy text,
  signal_strength decimal(5,4)
);

-- Table: portfolio_snapshots
-- Periodic snapshots of the user's portfolio for performance tracking
create table if not exists portfolio_snapshots (
  id uuid primary key default uuid_generate_v4(),
  user_id uuid references users(id) on delete cascade not null,
  timestamp timestamp with time zone default timezone('utc'::text, now()) not null,
  total_balance decimal(20,8) not null,
  available_balance decimal(20,8) not null,
  unrealized_pnl decimal(20,8) default 0,
  realized_pnl decimal(20,8) default 0,
  margin_ratio decimal(10,4) default 0
);

-- Table: signals
-- Stores trading signals generated by strategies for analysis and backtesting
create table if not exists signals (
  id uuid primary key default uuid_generate_v4(),
  user_id uuid references users(id) on delete cascade not null,
  timestamp timestamp with time zone default timezone('utc'::text, now()) not null,
  symbol text not null,
  side text not null check (side in ('BUY', 'SELL')),
  signal_strength decimal(5,4) not null check (signal_strength >= 0 and signal_strength <= 1),
  strategy text not null,
  metadata jsonb default '{}'::jsonb
);

-- Table: backtest_results
-- Stores results of backtest runs for performance analysis
create table if not exists backtest_results (
  id uuid primary key default uuid_generate_v4(),
  user_id uuid references users(id) on delete cascade not null,
  strategy text not null,
  symbol text not null,
  timeframe text not null,
  start_date timestamp with time zone not null,
  end_date timestamp with time zone not null,
  initial_capital decimal(20,8) not null,
  final_capital decimal(20,8) not null,
  total_return decimal(10,4) not null,
  sharpe_ratio decimal(10,4),
  max_drawdown decimal(10,4) not null,
  win_rate decimal(5,4) not null,
  total_trades integer not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Indexes for performance
create index if not exists idx_trading_state_user_id on trading_state(user_id);
create index if not exists idx_orders_user_id on orders(user_id);
create index if not exists idx_orders_timestamp on orders(timestamp);
create index if not exists idx_portfolio_snapshots_user_id on portfolio_snapshots(user_id);
create index if not exists idx_signals_user_id on signals(user_id);
create index if not exists idx_signals_timestamp on signals(timestamp);
create index if not exists idx_backtest_results_user_id on backtest_results(user_id);
create index if not exists idx_backtest_results_strategy on backtest_results(strategy);