import assert from 'node:assert/strict';
import { evaluateStrategies, scenarioCandles, walkForwardEvaluation } from '../evaluation/StrategyCouncilEvaluation';
import { BoardOfDirectorsEngine } from '../strategies/BoardOfDirectorsEngine';
import { evaluateCandleCouncil } from '../strategies/StrategyCouncil';
const candles = scenarioCandles('range', 420);
const options = { start: 100, end: 180, ablations: true };
const first = evaluateStrategies(candles, options), second = evaluateStrategies(candles, options);
assert.deepEqual(first, second, 'Identical seed/data must reproduce every decision and metric');
const changed = candles.map((c, i) => i < 200 ? c : { ...c, open: c.open * 2, close: c.close * 2, high: c.high * 2, low: c.low * 2 });
assert.deepEqual(first.observations, evaluateStrategies(changed, options).observations, 'Future data must not change past decisions');
const costs = evaluateStrategies(candles, { ...options, feeBps: 100 });
for (const key of Object.keys(first.summaries)) assert.ok(costs.summaries[key].netReturn <= first.summaries[key].netReturn + 1e-10);
const duplicate = [...candles]; duplicate[20] = { ...duplicate[19] };
assert.throws(() => evaluateStrategies(duplicate), /duplicate|gapped/);
assert.ok(evaluateCandleCouncil(candles.slice(0,100), { intervalMs: 60000, asOf: candles[110].timestamp }).every(x => x.side === 'ABSTAIN'));
const board = BoardOfDirectorsEngine.forEvaluation({ seed: 1, now: () => 0 });
assert.throws(() => board.holdMeeting({ symbol: 'BTC/USDT', candles: [], signals: [] }), /60 valid/);
const before = JSON.stringify(board.getStatusReport());
board.learnFromOutcome(100, 'BTC/USDT');
assert.equal(JSON.stringify(board.getStatusReport()), before, 'Estimated outcomes must not mutate live weights');
const wf = walkForwardEvaluation(candles);
assert.equal(wf.folds.length, 2);
for (const fold of wf.folds) {
  assert.ok(fold.test.config.start > fold.validationEnd);
  assert.ok(fold.test.observations.every(o => o.at > candles[fold.validationEnd].timestamp));
}
console.log('PASS reproducibility, past-only decisions, costs, missing/stale data, frozen live learning, purged walk-forward');
const { decide } = await import('../strategies/DecisionEngine');
const { FeatureEngine } = await import('../features/FeatureEngine');
const f = new FeatureEngine().extractFeatures('BTC/USDT', candles[100].close, candles.slice(0,101));
assert.equal(decide({ features: {...f, currentPrice:NaN} }),null);
assert.equal(decide({ features: {...f, hurstExponent:0.9,rsi14:80}, regime: { tradingAllowed:false } as any }),null);
const policyBefore = board.getActivePolicy();
const context = {tradeId:'verified-observation-1',symbol:'BTC/USDT',side:'BUY' as const,entryPrice:100,exitPrice:101,pnl:1,pnlPct:1,isWin:true,durationMinutes:5,isSimulation:true};
const observation = board.conductPostMortemDeliberation(context);
assert.equal(observation.round3Trials.length,0,'Never claim fabricated trials passed');
assert.deepEqual(board.getActivePolicy(),policyBefore,'Observations cannot auto-promote policies');
assert.equal(board.conductPostMortemDeliberation(context).id,observation.id);
assert.equal(board.getDeliberationSessions().length,1,'Repeated observation must be idempotent');
