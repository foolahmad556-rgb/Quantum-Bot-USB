import assert from 'node:assert/strict';
import { ExchangeMarketData } from '../market-data/ExchangeMarketData';
import { AssetScreener } from '../market-data/AssetScreener';
const market = new ExchangeMarketData(undefined, ['BTC/USDT']);
assert.equal(market.getFreshPrice('BTC/USDT'), undefined);
(market as any).currentPrices.set('BTC/USDT', 100);
(market as any).lastUpdateTimes.set('BTC/USDT', Date.now() - 31_000);
assert.equal(market.getFreshPrice('BTC/USDT'), undefined);
(market as any).lastUpdateTimes.set('BTC/USDT', Date.now());
assert.equal(market.getFreshPrice('BTC/USDT'), 100);
let covered: string[] = [];
market.startStreaming = (_, symbols) => { covered = symbols || []; };
market.ensureSymbols(['ETH/USDT']);
assert.deepEqual(covered, ['BTC/USDT', 'ETH/USDT']);
const screener = new AssetScreener();
(screener as any).fetchExchangeInfo = async () => ({ symbols: [{symbol:'BTCUSDT',status:'TRADING',contractType:'PERPETUAL',filters:[]}] });
(screener as any).fetch24hrTicker = async () => [{symbol:'BTCUSDT',quoteVolume:'100000000',priceChangePercent:'-1',highPrice:'101',lowPrice:'99'}];
(screener as any).fetchOrderBookDepth = async () => ({bidDepth:100000,askDepth:100000,spread:0.01});
await screener.refreshAllAssets();
assert.equal(screener.getAllAssets().length, 1, 'Futures ticker without bid/ask and with negative change must be screened');
console.log('PASS position price freshness, coverage and Futures ticker screening');
